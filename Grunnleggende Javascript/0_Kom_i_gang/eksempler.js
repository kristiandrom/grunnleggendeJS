// ---------- console.log() ----------

console.log("Hei, verden!");
console.log("Jeg lærer JavaScript.");

// Tall skrives uten anførselstegn
console.log(42);

// JavaScript regner ut svaret før det skrives ut
console.log(10 + 5);

// Med anførselstegn blir det tekst, og da regnes ingenting ut
console.log("10 + 5");

// Vi kan skrive ut flere ting på én linje ved å skille dem med komma
console.log("Svaret er", 10 + 5);

// En tom console.log() gir en tom linje
console.log();

// ---------- Rekkefølge ----------

